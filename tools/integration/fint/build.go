type ninjaDebugFileSet struct {
	// depsPath is an absolute path to a .ninja_deps
	depsPath string
	// tracePath is an absolute path to a ninjatrace JSON file, generated by the ninjatrace tool.
	// An empty value means the ninja trace was not generated.
	tracePath string
	// statsPath is an absolute path to a buildstats JSON file, generated by the buildstats tool.
	// An empty value means this output was not generated.
	statsPath string
}

type byTracePath []*ninjaDebugFileSet

// functions for sorting
func (n byTracePath) Len() int           { return len(n) }
func (n byTracePath) Swap(i, j int)      { n[i], n[j] = n[j], n[i] }
func (n byTracePath) Less(i, j int) bool { return n[i].tracePath < n[j].tracePath }

// subbuildEntry follows from the metadata written by GN to 'ninja_subbuilds.json'
type subbuildEntry struct {
	BuildDir string `json:"build_dir"`
}

func getSubbuildSubdirs(ctx context.Context, subbuildsJSON string) ([]string, error) {
	subbuildSubdirs := []string{}
	if checkFileExists(subbuildsJSON) {
		var subbuildEntries []subbuildEntry
		subbuildsData, err := os.ReadFile(subbuildsJSON)
		if err != nil {
			return nil, err
		}
		if err := json.Unmarshal(subbuildsData, &subbuildEntries); err != nil {
			return nil, err
		}
		for _, e := range subbuildEntries {
			subbuildSubdirs = append(subbuildSubdirs, e.BuildDir)
		}
	}
	return subbuildSubdirs, nil
}

// subninjaTraceIsRecent returns true if the mtime of the `log` is
// newer than time `t`.  This is passed a function to facilitate
// unit-testing.
func subninjaTraceIsRecent(log string, t time.Time) (bool, error) {
	info, err := os.Stat(log)
	if err != nil {
		return false, err
	}
	return t.Before(info.ModTime()), nil
}

func updateFileIfNeeded(filePath string, content []byte) error {
	if checkFileExists(filePath) {
		currentContent, err := os.ReadFile(filePath)
		if err != nil {
			return err
		}
		if bytes.Equal(currentContent, content) {
			return nil
		}
	}
	return os.WriteFile(filePath, content, 0o644)
}

// Build runs `ninja` given a static and context spec. It's intended to be
// consumed as a library function.
func Build(ctx context.Context, staticSpec *fintpb.Static, contextSpec *fintpb.Context) (*fintpb.BuildArtifacts, error) {
	platform, err := hostplatform.Name()
	if err != nil {
		return nil, err
	}
	buildDir := contextSpec.BuildDir
	modules, err := build.NewModules(buildDir)
	if err != nil {
		return nil, err
	}

	client, err := build.NewBuildAPIClient(buildDir)
	if err != nil {
		return nil, err
	}

	artifacts, err := buildImpl(ctx, newRunner(contextSpec), subninjaTraceIsRecent, checkFileExists, staticSpec, contextSpec, modules, client, platform)
	if err != nil && artifacts != nil && artifacts.FailureSummary == "" {
		// Fall back to using the error text as the failure summary if the
		// failure summary is unset. It's better than failing without emitting
		// any information.
		artifacts.FailureSummary = err.Error()
	}
	return artifacts, err
}

// buildImpl contains the business logic of `fint build`, extracted into a more
// easily testable layer.
func buildImpl(
	ctx context.Context,
	runner subprocessRunner,
	subninjaTraceIsRecent func(string, time.Time) (bool, error),
	fileExists func(string) bool,
	staticSpec *fintpb.Static,
	contextSpec *fintpb.Context,
	modules buildModules,
	buildAPIClient buildAPIClient,
	platform string,
) (*fintpb.BuildArtifacts, error) {
	buildDir := contextSpec.BuildDir
	if staticSpec.Incremental {
		// If we're building incrementally, we need to rebuild all nonhermetic
		// actions. This is done by touching a particular file in the build
		// directory.
		path := filepath.Join(append([]string{buildDir}, rebuildNonHermeticActionsPath...)...)
		if err := runner.Run(ctx, []string{"touch", filepath.Join(path)}, subprocess.RunOptions{}); err != nil {
			return nil, err
		}
	}

	artifacts := &fintpb.BuildArtifacts{}

	targets, targetArtifacts, err := constructNinjaTargets(modules, staticSpec, contextSpec, platform)
	if err != nil {
		return artifacts, err
	}
	proto.Merge(artifacts, targetArtifacts)

	// Initialize maps, otherwise they will be nil and attempts to set keys will
	// fail.
	artifacts.LogFiles = make(map[string]string)
	artifacts.NonFatalFailures = make(map[string]string)

	ninjaName := "ninja"
	if staticSpec.BuildEventServiceNinja == "resultstore_infra" {
		ninjaName = "rs-sub-ninja"
	}
	ninjaPath, err := toolAbsPath(modules, platform, ninjaName)
	if err != nil {
		return artifacts, err
	}
	jobCount := int(contextSpec.JobCount)
	jobserverPool := false
	for _, arg := range staticSpec.GnArgs {
		if strings.ReplaceAll(arg, " ", "") == "enable_jobserver=true" {
			jobserverPool = true
			break
		}
	}
	r := ninjaRunner{
		runner:    runner,
		ninjaPath: ninjaPath,
		buildDir:  buildDir,
		jobCount:  jobCount,
	}

	buildSuccessStampPath := filepath.Join(buildDir, buildSuccessStampName)
	if checkFileExists(buildSuccessStampPath) {
		err = os.Remove(buildSuccessStampPath)
		if err != nil {
			return nil, err
		}
	}

	updateFileIfNeeded(filepath.Join(buildDir, lastNinjaBuildTargetsName),
		[]byte(strings.Join(targets, " ")))

	os.WriteFile(filepath.Join(buildDir, lastBazelBuildInvocationsName),
		[]byte("[]"), 0o644)

	// Tell Ninja to generate a compressed Chrome trace after the build completes.
	// Also emit a metrics file that contains action counts by mnemonic.
	ninjaExtraArgs := []string{
		"--chrome_trace", ninjaBuildTraceName,
		"--action_metrics_output", actionMetricsName,
	}

	if jobserverPool {
		ninjaExtraArgs = append(ninjaExtraArgs, "--jobserver")
	}

	ninjaStartTime := time.Now()
	var ninjaErr error
	if contextSpec.ArtifactDir == "" {
		// If we don't care about collecting artifacts, which is generally the
		// case when running locally, then there's no need to parse the Ninja
		// stdout to get the failure message. So let Ninja print directly to
		// stdout, so it will nicely buffer output when running in a terminal
		// instead of printing each log on a new line.
		_, ninjaErr = r.run(ctx, append(append(staticSpec.NinjaArgs, ninjaExtraArgs...), targets...), os.Stdout, os.Stderr)
	} else {
		var explainSink io.Writer
		if staticSpec.Incremental {
			f, err := os.Create(filepath.Join(contextSpec.ArtifactDir, "explain_output.txt"))
			if err != nil {
				return artifacts, err
			}
			defer f.Close()
			artifacts.LogFiles["explain_output.txt"] = f.Name()
			explainSink = f
		}
		artifacts.FailureSummary, artifacts.NinjaActionMetrics, ninjaErr = runNinja(
			ctx,
			r,
			append(staticSpec.NinjaArgs, ninjaExtraArgs...),
			targets,
			// Add -d explain to incremental builds.
			staticSpec.Incremental,
			explainSink,
		)
	}

	// Only write the build success stamp file if the build succeeded.
	if ninjaErr == nil {
		err = os.WriteFile(buildSuccessStampPath, []byte{}, 0o644)
		if err != nil {
			return nil, err
		}
	}

	ninjaDuration := time.Since(ninjaStartTime)
	artifacts.NinjaDurationSeconds = int32(math.Round(ninjaDuration.Seconds()))

	// Similar to `fx ninjatrace2json`, generate and collect ninja traces
	// in each (sub)build dir where ninja is invoked.
	ninjatraceToolPath, err := toolAbsPath(modules, platform, "ninjatrace_prebuilt")
	if err != nil {
		return artifacts, err
	}

	// Collect buildstats in each ninja (sub)build dir.
	buildstatsToolPath, err := toolAbsPath(modules, platform, "buildstats_prebuilt")
	if err != nil {
		return artifacts, err
	}

	// Each ninja invocation produces a log file located in its build dir.
	// Depending on the status of the build, not all sub-build logs are guaranteed to exist.
	topNinjaTrace := filepath.Join(buildDir, ninjaBuildTraceName)
	subbuildsJSON := filepath.Join(buildDir, subbuildsJSONName)
	subbuildSubdirs, err := getSubbuildSubdirs(ctx, subbuildsJSON)
	if err != nil {
		return nil, err
	}
	subNinjaTraceCandidates := []string{}
	for _, subdir := range subbuildSubdirs {
		subninjaTrace := filepath.Join(buildDir, subdir, ninjaBuildTraceName)
		if !fileExists(subninjaTrace) {
			continue
		}
		// A ninja trace could exist from a previous build,
		// so only take traces that were touched since the start time.
		recent, err := subninjaTraceIsRecent(subninjaTrace, ninjaStartTime)
		if err != nil {
			return nil, err
		}
		if !recent {
			continue
		}
		subNinjaTraceCandidates = append(subNinjaTraceCandidates, subninjaTrace)
	}

	// Process ninja traces (top and sub-builds), in parallel.
	ninjaFileSetChan := make(chan *ninjaDebugFileSet, len(subNinjaTraceCandidates)+1)
	eg, egCtx := errgroup.WithContext(ctx)
	// Handle top-level build differently, pass targets
	eg.Go(func() error {
		subninjaRunner := ninjaRunner{
			runner:    runner,
			ninjaPath: ninjaPath,
			buildDir:  buildDir,
		}
		fs, err := getNinjaDebugFiles(egCtx, subninjaRunner, topNinjaTrace, ninjatraceToolPath, buildstatsToolPath)
		if err != nil {
			logger.Warningf(ctx, "(ignored) Failed to analyze top ninja log %s, with error: %v", topNinjaTrace, err)
			return nil
		}
		ninjaFileSetChan <- fs
		return nil
	})
	for _, ninjaTrace := range subNinjaTraceCandidates { // sub-builds
		ninjaBuildTrace := ninjaTrace
		eg.Go(func() error {
			// `egCtx` allows errgroup to cancel other goroutines as soon as one of them errors.
			subninjaRunner := ninjaRunner{
				runner:    runner,
				ninjaPath: ninjaPath,
				buildDir:  filepath.Dir(ninjaBuildTrace),
			}
			fs, err := getNinjaDebugFiles(egCtx, subninjaRunner, ninjaBuildTrace, ninjatraceToolPath, buildstatsToolPath)
			if err != nil {
				logger.Warningf(ctx, "(ignored) Failed to analyze sub ninja log %s, with error: %v", ninjaBuildTrace, err)
				return nil
			}
			ninjaFileSetChan <- fs
			return nil
		})
	}
	if err := eg.Wait(); err != nil {
		return artifacts, err
	}
	// Pull file sets from channel into array.
	close(ninjaFileSetChan)
	var ninjaDebugFileSets []*ninjaDebugFileSet
	for fs := range ninjaFileSetChan {
		ninjaDebugFileSets = append(ninjaDebugFileSets, fs)
	}
	// Make ordering deterministic for the sake of testing.
	sort.Sort(byTracePath(ninjaDebugFileSets))

	if contextSpec.ArtifactDir != "" {
		for _, debugFileSet := range ninjaDebugFileSets {
			if debugFileSet.tracePath != "" {
				artifacts.NinjatraceJsonFiles = append(artifacts.NinjatraceJsonFiles, debugFileSet.tracePath)
			}
			if debugFileSet.statsPath != "" {
				artifacts.BuildstatsJsonFiles = append(artifacts.BuildstatsJsonFiles, debugFileSet.statsPath)
			}
		}
	}

	saveDebugFiles := func(paths []string) error {
		for _, path := range paths {
			rel, err := filepath.Rel(buildDir, path)
			if err != nil {
				return err
			}
			artifacts.DebugFiles = append(artifacts.DebugFiles, &fintpb.DebugFile{
				Path:       path,
				UploadDest: filepath.ToSlash(rel),
			})
		}
		return nil
	}

	if ninjaErr != nil {
		if contextSpec.ArtifactDir != "" {
			if err := func() error {
				crashReportFiles, err := collectClangCrashReports(buildDir)
				if err != nil {
					return err
				}
				if err := saveDebugFiles(crashReportFiles); err != nil {
					return err
				}

				compareDiagnosticsFiles, err := collectCompareDiagnosticsFiles(buildDir)
				if err != nil {
					return err
				}
				if err := saveDebugFiles(compareDiagnosticsFiles); err != nil {
					return err
				}

				traces, err := collectFileAccessTraces(buildDir)
				if err != nil {
					return fmt.Errorf("collecting file access traces: %w", err)
				}
				if err := saveDebugFiles(traces); err != nil {
					return fmt.Errorf("writing file access traces to debug files: %w", err)
				}
				return nil
			}(); err != nil {
				logger.Warningf(ctx, "Failed to collect debug files: %s", err)
			}
		}
		return artifacts, fmt.Errorf("build failed, see ninja output for details: %w", ninjaErr)
	}

	gnPath, err := toolAbsPath(modules, platform, "gn")
	if err != nil {
		return artifacts, err
	}
	if output, err := gnCheckGenerated(ctx, runner, gnPath, contextSpec.CheckoutDir, buildDir); err != nil {
		artifacts.FailureSummary = output
		return artifacts, err
	}

	if !contextSpec.SkipNinjaNoopCheck {
		noop, msg, logs, err := checkNinjaNoop(ctx, r, targets, hostplatform.IsMac(platform))
		if err != nil {
			return artifacts, err
		}
		if err := saveLogs(contextSpec.ArtifactDir, artifacts, logs); err != nil {
			return artifacts, err
		}
		if !noop {
			// Upload additional ninja files to help with debugging.
			ninjaDebugFilePaths := collectNinjaArtifacts(ninjaDebugFileSets, fileExists)
			if err := saveDebugFiles(ninjaDebugFilePaths); err != nil {
				return artifacts, err
			}

			if contextSpec.ArtifactDir != "" {
				buildDirManifest := filepath.Join(contextSpec.ArtifactDir, "build_dir_manifest.json")
				if err := writeBuildDirManifest(buildDir, buildDirManifest); err != nil {
					logger.Warningf(ctx, "Failed to create manifest of build dir contents: %s", err)
				} else {
					artifacts.DebugFiles = append(artifacts.DebugFiles, &fintpb.DebugFile{
						Path:       buildDirManifest,
						UploadDest: "build_dir_manifest.json",
					})
				}
			}

			artifacts.FailureSummary = ninjaNoopFailureMessage(platform, msg)
			return artifacts, fmt.Errorf("ninja build did not converge to no-op")
		}
	}

	var outputBreakpadSyms bool
	if err := modules.Args().Get("output_breakpad_syms", &outputBreakpadSyms); err != nil && !errors.Is(err, build.ErrArgNotSet) {
		return artifacts, err
	}

	symbolDir := filepath.Join(contextSpec.BuildDir, "debug_symbols")
	if err := os.RemoveAll(symbolDir); err != nil {
		return artifacts, err
	}
	if err := os.MkdirAll(symbolDir, 0o700); err != nil {
		return artifacts, err
	}
	symbolsJSON, err := exportDebugSymbols(ctx, buildAPIClient, contextSpec, symbolDir, outputBreakpadSyms)
	if err != nil {
		return artifacts, err
	}
	if symbolsJSON != "" {
		if err := saveLogs(contextSpec.ArtifactDir, artifacts, map[string]string{
			"debug_symbols.json": symbolsJSON,
		}); err != nil {
			return artifacts, err
		}
	}
	if summary, err := buildBazelTests(ctx, runner, contextSpec.CheckoutDir, contextSpec.BuildDir, modules.TestSpecs()); err != nil {
		if summary != "" {
			artifacts.FailureSummary = summary
		}
		return artifacts, err
	}

	// TODO(olivernewman): Figure out a way to skip this analysis when the
	// caller doesn't care about running tests, or just wants to run all tests
	// in the same way regardless of any build graph analysis. In the meantime
	// it's not the end of the world to do this analysis unnecessarily, since it
	// only takes ~10 seconds and we do use the results most of the time,
	// including on all the slowest infra builders.
	newArtifacts, err := affectedImpl(ctx, runner, buildAPIClient, contextSpec, modules, platform, targets)
	if err != nil {
		return artifacts, err
	}
	proto.Merge(artifacts, newArtifacts)
	return artifacts, nil
}

// getNinjaDebugFiles creates a ninja trace file that will be exposed for debugging.
func getNinjaDebugFiles(ctx context.Context, r ninjaRunner, ninjaTrace string, ninjatraceToolPath string, buildstatsToolPath string) (*ninjaDebugFileSet, error) {
	// Write auxiliary files and the final ninja trace to the same dir where the ninja log resides.
	// This this assumes that the build dir is writeable.
	logger.Debugf(ctx, "analyzing ninja trace: %s", ninjaTrace)
	subBuildDirAbs := filepath.Dir(ninjaTrace)

	ninjaDepsFile := filepath.Join(subBuildDirAbs, ninjaDepsPath)

	debugFiles := &ninjaDebugFileSet{
		depsPath: ninjaDepsFile,
		// tracePath and statsPath set below after being generated
	}

	ninjatraceJSON := filepath.Join(subBuildDirAbs, ninjatraceJSONName)
	if err := runNinjatrace(ctx, r.runner, ninjatraceToolPath, ninjaTrace, ninjatraceJSON); err != nil {
		return debugFiles, err
	}
	debugFiles.tracePath = ninjatraceJSON

	buildstatsJSON := filepath.Join(subBuildDirAbs, buildstatsJSONName)
	if err := runBuildstats(ctx, r.runner, buildstatsToolPath, ninjatraceJSON, buildstatsJSON); err != nil {
		return debugFiles, err
	}
	debugFiles.statsPath = buildstatsJSON

	return debugFiles, nil
}

func collectNinjaArtifacts(ninjaDebugFiles []*ninjaDebugFileSet, fileExists func(string) bool) []string {
	var paths []string
	for _, ndf := range ninjaDebugFiles {
		files := []string{ndf.depsPath, ndf.tracePath, ndf.statsPath}
		for _, f := range files {
			if fileExists(f) {
				paths = append(paths, f)
			}
		}
	}
	return paths
}

// collectClangCrashReports finds reproducer scripts for clang crashes in the
// build directory and returns a list of absolute paths to those files.
func collectClangCrashReports(buildDir string) ([]string, error) {
	crashReportsDir := filepath.Join(buildDir, clangCrashReportsDirName)
	if isDir, err := osmisc.IsDir(crashReportsDir); err != nil || !isDir {
		return nil, err
	}

	allFiles, err := filepath.Glob(filepath.Join(crashReportsDir, "*"))
	if err != nil {
		return nil, err
	}

	fileSet := make(map[string]struct{})
	for _, file := range allFiles {
		fileSet[file] = struct{}{}
	}

	reproducers, err := filepath.Glob(filepath.Join(crashReportsDir, "*.sh"))
	if err != nil {
		return nil, err
	}

	var outputs []string
	for _, rep := range reproducers {
		noExt := strings.TrimSuffix(rep, filepath.Ext(rep))
		files, err := filepath.Glob(noExt + ".*")
		if err != nil {
			return nil, err
		}

		tarball, err := os.Create(noExt + ".tar")
		if err != nil {
			return nil, err
		}
		defer tarball.Close()

		tw := tar.NewWriter(tarball)
		defer tw.Close()

		for _, file := range files {
			f, err := os.Open(file)
			if err != nil {
				return nil, err
			}
			defer f.Close()

			info, err := f.Stat()
			if err != nil {
				return nil, err
			}

			header, err := tar.FileInfoHeader(info, info.Name())
			if err != nil {
				return nil, err
			}

			err = tw.WriteHeader(header)
			if err != nil {
				return nil, err
			}

			_, err = io.Copy(tw, f)
			if err != nil {
				return nil, err
			}

			delete(fileSet, file)
		}
		outputs = append(outputs, noExt+".tar")
	}

	for file := range fileSet {
		outputs = append(outputs, file)
	}

	return outputs, nil
}

// collectCompareDiagnosticsFiles lists absolute paths to files in the
// comparison diffs directory, which can be populated by determinism
// and consistency checks.
func collectCompareDiagnosticsFiles(buildDir string) ([]string, error) {
	var files []string
	diagnosticsDir := filepath.Join(buildDir, comparisonDiagnosticsDirName)
	if isDir, err := osmisc.IsDir(diagnosticsDir); err != nil || !isDir {
		return nil, err
	}
	err := filepath.WalkDir(diagnosticsDir, func(path string, info fs.DirEntry, err error) error {
		if err != nil {
			return err
		}
		if !info.IsDir() {
			files = append(files, path)
		}
		return nil
	})
	if err != nil {
		return nil, err
	}
	return files, nil
}

// collectFileAccessTraces finds access traces in the build directory, and
// returns paths to them. Note this function returns absolute paths because they
// are expected by `debug_files`.
func collectFileAccessTraces(buildDir string) ([]string, error) {
	var traces []string
	err := filepath.WalkDir(filepath.Join(buildDir, fileAccessTracesDirName), func(path string, info fs.DirEntry, err error) error {
		if err != nil {
			return err
		}
		if !info.IsDir() && strings.HasSuffix(path, fileAccessTracesSuffix) {
			traces = append(traces, path)
		}
		return nil
	})
	if err != nil {
		return nil, err
	}
	return traces, nil
}

func ninjaNoopFailureMessage(platform, ninjaMsg string) string {
	summaryLines := []string{
		"Ninja build did not converge to no-op.",
		"See: https://fuchsia.dev/fuchsia-src/development/build/ninja_no_op",
	}
	if hostplatform.IsMac(platform) {
		summaryLines = append(
			summaryLines,
			"If this failure is specific to Mac, confirm that it's not related to https://fxbug.dev/42140108.",
		)
	}
	if ninjaMsg != "" {
		summaryLines = append(
			summaryLines,
			"",
			"First line of ninja explain output:",
			"",
			ninjaMsg)
	}
	return strings.Join(summaryLines, "\n")
}

// constructNinjaTargets determines which targets to build based on the static
// spec fields and the contents of the build API files. It emits a
// BuildArtifacts protobuf with only a subset of fields set that should be
// merged into an existing BuildArtifacts protobuf struct by the caller, since
// this is more clean than taking a BuildArtifacts pointer as input and
// modifying it.
func constructNinjaTargets(
	modules buildModules,
	staticSpec *fintpb.Static,
	contextSpec *fintpb.Context,
	platform string,
) ([]string, *fintpb.BuildArtifacts, error) {
	var targets []string
	var artifacts fintpb.BuildArtifacts

	if staticSpec.IncludeArchives {
		return nil, nil, fmt.Errorf("include_archives=true is no longer supported")
	}

	if staticSpec.IncludeDefaultNinjaTarget {
		targets = append(targets, ":default")
	} else {
		// "//:host" is a dep of "//:default"
		if staticSpec.IncludeHostTests {
			for _, testSpec := range modules.TestSpecs() {
				if testSpec.OS != "fuchsia" {
					targets = append(targets, testSpec.Path)
				}
			}
		}
	}

	if staticSpec.IncludeGeneratedSources {
		for _, f := range modules.GeneratedSources() {
			// TODO(https://fxbug.dev/42066838): Remove support for building generated
			// sources directly. It's only necessary to make generated FIDL
			// files available when running Clang-Tidy in presubmit, but
			// Clang-Tidy should be integrated into the build system so that the
			// necessary generated files are built automatically when Clang-Tidy
			// is run.
			if slices.Contains([]string{".cc", ".h"}, filepath.Ext(f)) {
				targets = append(targets, f)
			}
		}
	}

	if staticSpec.IncludePrebuiltBinaryManifests {
		for _, manifest := range modules.PrebuiltBinarySets() {
			targets = append(targets, manifest.Manifest)
		}
	}

	lintTargets, err := chooseLintTargets(modules, staticSpec, contextSpec)
	if err != nil {
		return nil, nil, err
	}
	targets = append(targets, lintTargets...)

	// We only support specifying tools for the current platform. Tools
	// needed for other platforms can be included in the build indirectly
	// via higher-level targets.
	for _, tool := range staticSpec.Tools {
		t, err := modules.Tools().LookupTool(platform, tool)
		if err != nil {
			return nil, nil, err
		}
		targets = append(targets, t.Path)
	}

	targets = append(targets, staticSpec.NinjaTargets...)
	return removeDuplicates(targets), &artifacts, nil
}

func chooseLintTargets(
	modules buildModules,
	staticSpec *fintpb.Static,
	contextSpec *fintpb.Context,
) ([]string, error) {
	if staticSpec.IncludeLintTargets == fintpb.Static_NO_LINT_TARGETS {
		return nil, nil
	}

	changed := make(map[string]bool)
	for _, f := range contextSpec.ChangedFiles {
		changed[f.Path] = true
	}

	shouldInclude := func(sources []string) (bool, error) {
		if staticSpec.IncludeLintTargets == fintpb.Static_ALL_LINT_TARGETS {
			return true, nil
		} else if staticSpec.IncludeLintTargets != fintpb.Static_AFFECTED_LINT_TARGETS {
			return false, fmt.Errorf("unknown include_lint_targets value: %s", staticSpec.IncludeLintTargets)
		}
		for _, source := range sources {
			checkoutPath, err := filepath.Rel(
				contextSpec.CheckoutDir,
				filepath.Clean(filepath.Join(contextSpec.BuildDir, source)))
			if err != nil {
				return false, err
			}
			if changed[filepath.ToSlash(checkoutPath)] {
				return true, nil
			}
		}
		return false, nil
	}

	var targets []string
	for _, clippy := range modules.ClippyTargets() {
		if clippy.DisableClippy {
			continue
		}
		include, err := shouldInclude(clippy.Sources)
		if err != nil {
			return nil, err
		}
		if include {
			targets = append(targets, clippy.Output)
		}
	}
	return targets, nil
}

// toolAbsPath returns the absolute path to a tool specified in tool_paths.json.
//
// Note that not all tools in tool_paths.json can be assumed to be present in
// the build directory prior to `fint build` running because only a subset of
// them are prebuilts, and the rest are built from source.
func toolAbsPath(modules buildModules, platform, tool string) (string, error) {
	t, err := modules.Tools().LookupTool(platform, tool)
	if err != nil {
		return "", err
	}
	return filepath.Abs(filepath.Join(modules.BuildDir(), t.Path))
}

// toStructPB converts a Go struct to a Struct protobuf. Unfortunately, short of
// using some complicated `reflect` logic, the only way to do this conversion is
// by using JSON as an intermediate format.
func toStructPB(s any) (*structpb.Struct, error) {
	j, err := json.Marshal(s)
	if err != nil {
		return nil, err
	}
	var m map[string]any
	if err := json.Unmarshal(j, &m); err != nil {
		return nil, err
	}
	return structpb.NewStruct(m)
}

// removeDuplicates returns a slice containing only the unique elements of the
// original slice.
func removeDuplicates(slice []string) []string {
	uniq := make(map[string]struct{})
	for _, str := range slice {
		uniq[str] = struct{}{}
	}
	var deduped []string
	for str := range uniq {
		deduped = append(deduped, str)
	}
	// Sort to make the output deterministic for unit tests.
	sort.Strings(deduped)
	return deduped
}

// gnCheckGenerated runs `gn check` against a build directory that's already had
// `ninja` run, to check generated files that weren't available for checking at
// the time we ran `fint set`.
//
// It returns the stdout of the subprocess.
func gnCheckGenerated(ctx context.Context, r subprocessRunner, gn, checkoutDir, buildDir string) (string, error) {
	cmd := []string{
		gn,
		"check",
		buildDir,
		fmt.Sprintf("--root=%s", checkoutDir),
		"--check-generated",
		"--check-system",
	}
	var stdoutBuf bytes.Buffer
	if err := r.Run(ctx, cmd, subprocess.RunOptions{Stdout: io.MultiWriter(&stdoutBuf, os.Stdout)}); err != nil {
		return stdoutBuf.String(), fmt.Errorf("error running `gn check`: %w", err)
	}
	return stdoutBuf.String(), nil
}

type buildDirManifestElement struct {
	// Path is the path to the file, relative to the build directory root.
	Path string `json:"path"`
	// SyminkTarget is only set if this file is a symlink, and specifies the
	// path that the symlink points to.
	SymlinkTarget string `json:"symlink_target,omitempty"`
	// ModTimeMilliseconds is the modification time of the file, in the form of
	// a Unix millisecond timestamp for consistency with the timestamp format
	// that ninja uses.
	ModTimeMilliseconds float64 `json:"mtime"`
}

// writeBuildDirManifest constructs a manifest of all the files in the build
// directory and writes it as JSON to `outputPath`. This manifest is useful for
// debugging incremental build failures.
func writeBuildDirManifest(buildDir string, outputPath string) error {
	// Empty slice instead of nil so it gets rendered as an empty JSON array
	// instead of null.
	ret := []buildDirManifestElement{}

	if err := filepath.WalkDir(buildDir, func(path string, d fs.DirEntry, err error) error {
		if err != nil {
			return err
		}
		if d.IsDir() {
			return nil
		}

		info, err := d.Info()
		if err != nil {
			return err
		}

		relpath, err := filepath.Rel(buildDir, path)
		if err != nil {
			return err
		}

		var symlinkTarget string
		if d.Type()&fs.ModeSymlink != 0 {
			symlinkTarget, err = os.Readlink(path)
			if err != nil {
				return err
			}
		}

		ret = append(ret, buildDirManifestElement{
			Path:          filepath.ToSlash(relpath),
			SymlinkTarget: filepath.ToSlash(symlinkTarget),
			// Note that for symlinks this is the mtime of the symlink itself,
			// rather than the mtime of the target of the symlink.
			ModTimeMilliseconds: float64(info.ModTime().UnixMicro()) / float64(time.Millisecond/time.Microsecond),
		})
		return nil
	}); err != nil {
		return err
	}

	return jsonutil.WriteToFile(outputPath, ret)
}

// exportDebugSymbols exports debug symbols to the give `outputDir` and returns
// the contents of the generated `debug_symbols.json` file.
func exportDebugSymbols(ctx context.Context, buildAPIClient buildAPIClient, contextSpec *fintpb.Context, outputDir string, withBreakpad bool) (string, error) {
	if err := buildAPIClient.ExportDebugSymbols(ctx, outputDir, withBreakpad); err != nil {
		return "", err
	}

	b, err := os.ReadFile(filepath.Join(outputDir, "debug_symbols.json"))
	if err != nil {
		return "", err
	}

	return string(b), nil
}

func buildBazelTests(ctx context.Context, runner subprocessRunner, checkoutDir, buildDir string, testSpecs []build.TestSpec) (string, error) {
	var bazelLabels []string
	for _, spec := range testSpecs {
		// Bazel tests are differentiated from GN tests by having a "@" prefix
		// in the label field.
		if strings.HasPrefix(spec.Label, "@") {
			bazelLabels = append(bazelLabels, spec.Label)
		}
	}
	if len(bazelLabels) == 0 {
		return "", nil
	}

	topDirConfigPath := filepath.Join(checkoutDir, "build", "bazel", "config", "bazel_top_dir")
	data, err := os.ReadFile(topDirConfigPath)
	if err != nil {
		return "", fmt.Errorf("failed to read bazel_top_dir config at %s: %w", topDirConfigPath, err)
	}
	bazelTopDir := strings.TrimSpace(string(data))
	bazelLauncher := filepath.Join(buildDir, bazelTopDir, "bazel")
	if _, err := os.Stat(bazelLauncher); err != nil {
		if os.IsNotExist(err) {
			return "", fmt.Errorf("bazel launcher not found at %s: check if the workspace was properly initialized by GN/Ninja", bazelLauncher)
		}
		return "", err
	}

	cmd := append([]string{
		bazelLauncher,
		"build",
		// For now we only support building Bazel host tests.
		// TODO(https://fxbug.dev/546173288): Support Bazel target tests.
		"--config=host",
		// Bazel prefers to wait until the latest possible moment (e.g. `bazel
		// test`) to generate runfiles. Forcing runfile link generation during
		// `bazel build` ensures all runtime dependencies are materialized under
		// the execroot where the test runner expects them.
		"--build_runfile_links=true",
		"--enable_runfiles=true",
	}, bazelLabels...)

	var stderrBuf bytes.Buffer
	if err := runner.Run(ctx, cmd, subprocess.RunOptions{
		Stdout: os.Stdout,
		Stderr: io.MultiWriter(os.Stderr, &stderrBuf),
	}); err != nil {
		return parseBazelError(stderrBuf.String()), fmt.Errorf("failed to build Bazel tests: %w", err)
	}
	return "", nil
}

var bazelProgressRe = regexp.MustCompile(`^\[\d+(?:,\d+)* / \d+(?:,\d+)*\]`)

// parseBazelError parses the standard error output of a bazel command and
// extracts the meaningful error messages, filtering out progress and unhelpful
// log messages.
func parseBazelError(stderr string) string {
	var out []string
	lines := strings.Split(stderr, "\n")

	ignorePrefixes := []string{
		"INFO:",
		"WARNING:",
		"Loading:",
		"Analyzing:",
		"Computing main repo mapping:",
		"ERROR: Build did NOT complete successfully",
		"Use --verbose_failures to see the command lines of failed build steps.",
	}

	for _, line := range lines {
		ignore := false
		for _, prefix := range ignorePrefixes {
			if strings.HasPrefix(line, prefix) {
				ignore = true
			}
		}
		if ignore {
			continue
		}

		if bazelProgressRe.MatchString(line) {
			continue
		}

		out = append(out, line)
	}

	return strings.TrimSpace(strings.Join(out, "\n"))
}

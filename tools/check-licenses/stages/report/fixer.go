package report

import (
	"context"
	"fmt"
	"os"
	"path/filepath"
	"sort"
	"sync"

	"go.fuchsia.dev/fuchsia/tools/check-licenses/config"
	"go.fuchsia.dev/fuchsia/tools/check-licenses/pipeline"
	"go.fuchsia.dev/fuchsia/tools/check-licenses/stages/validate"
)

// Policy check names corresponding to compliance engine rules.
const (
	CheckNameReadmeFuchsiaNeedsUpdate                              = validate.CheckReadmeNeedsUpdate
	PolicyCheckAllFuchsiaAuthorSourceFilesMustHaveCopyrightHeaders = validate.PolicyFuchsiaCopyright
	PolicyCheckAllProjectsMustHaveALicense                         = validate.PolicyNoLicense
	PolicyCheckAllLicenseTextsMustBeRecognized                     = validate.PolicyUnrecognizedLicense
	CheckNameAllLicensePatternUsagesMustBeApproved                 = validate.CheckPatternApproval
)

// FixerRenderer is a Stage 6 renderer that mutates disk to automatically resolve
// policy compliance errors emitted by Stage 5.
type FixerRenderer struct {
	FuchsiaDir     string
	Config         *config.MasterConfig
	FixedCount     map[string][]string
	NewConfigFiles []string
	mu             sync.Mutex
}

// NewFixerRenderer creates a new FixerRenderer.
func NewFixerRenderer(fuchsiaDir string, cfg *config.MasterConfig) *FixerRenderer {
	return &FixerRenderer{
		FuchsiaDir: fuchsiaDir,
		Config:     cfg,
		FixedCount: make(map[string][]string),
	}
}

func (r *FixerRenderer) Run(ctx context.Context, projects []*pipeline.Project, errors []pipeline.ComplianceError) error {
	for _, e := range errors {
		fmt.Printf(" [Fixer] Processing error: %s (%s)\n", e.CheckName, e.FilePath)
		r.applyFix(e)
	}
	return nil
}

func (r *FixerRenderer) applyFix(e pipeline.ComplianceError) {
	r.mu.Lock()
	defer r.mu.Unlock()

	switch e.CheckName {
	case CheckNameReadmeFuchsiaNeedsUpdate:
		r.FixedCount["README Updates"] = append(r.FixedCount["README Updates"], e.FilePath)

	case PolicyCheckAllFuchsiaAuthorSourceFilesMustHaveCopyrightHeaders:
		if err := r.applyCopyrightFix(e.FilePath); err != nil {
			fmt.Fprintf(os.Stderr, " [Fixer] Failed to apply copyright fix for %s: %v\n", e.FilePath, err)
		} else {
			r.FixedCount["Copyright Headers"] = append(r.FixedCount["Copyright Headers"], e.FilePath)
		}

	case PolicyCheckAllProjectsMustHaveALicense:
		if path, err := r.addPolicyException(e.CheckName, e.Project, "TODO: Auto-generated by fx check-licenses fix", "Auto-generated exception via fix"); err != nil {
			fmt.Fprintf(os.Stderr, " [Fixer] Failed to add policy exception for %s: %v\n", e.Project, err)
		} else {
			r.FixedCount["Policy Exceptions (Missing License)"] = append(r.FixedCount["Policy Exceptions (Missing License)"], e.Project)
			if path != "" {
				r.NewConfigFiles = append(r.NewConfigFiles, path)
			}
		}

	case PolicyCheckAllLicenseTextsMustBeRecognized:
		if path, err := r.addPolicyException(e.CheckName, e.FilePath, "TODO: Auto-generated by fx check-licenses fix", "Auto-generated exception via fix"); err != nil {
			fmt.Fprintf(os.Stderr, " [Fixer] Failed to add policy exception for %s: %v\n", e.FilePath, err)
		} else {
			r.FixedCount["Policy Exceptions (Unrecognized License)"] = append(r.FixedCount["Policy Exceptions (Unrecognized License)"], e.FilePath)
			if path != "" {
				r.NewConfigFiles = append(r.NewConfigFiles, path)
			}
		}

	case CheckNameAllLicensePatternUsagesMustBeApproved:
		if path, err := r.addAllowlistEntry(e.LicenseID, e.Project, "TODO: Auto-generated by fx check-licenses fix", "Auto-generated allowlist entry via fix"); err != nil {
			fmt.Fprintf(os.Stderr, " [Fixer] Failed to add allowlist entry for %s: %v\n", e.Project, err)
		} else {
			r.FixedCount["Allowlist Entries ("+e.LicenseID+")"] = append(r.FixedCount["Allowlist Entries ("+e.LicenseID+")"], e.Project)
			if path != "" {
				r.NewConfigFiles = append(r.NewConfigFiles, path)
			}
		}
	}
}

func (r *FixerRenderer) applyCopyrightFix(filePath string) error {
	absPath := filePath
	if !filepath.IsAbs(filePath) {
		absPath = filepath.Join(r.FuchsiaDir, filePath)
	}

	hasCopyright, err := validate.CheckCopyright(absPath)
	if err != nil {
		return err
	}
	if hasCopyright {
		return nil
	}

	newBytes, err := validate.AddCopyright(absPath)
	if err != nil {
		return err
	}

	if err := os.WriteFile(absPath, newBytes, 0644); err != nil {
		return fmt.Errorf("failed to write file: %w", err)
	}
	return nil
}

func (r *FixerRenderer) addPolicyException(checkName, targetPath, bug, description string) (string, error) {
	if r.Config == nil {
		return "", fmt.Errorf("config is nil")
	}
	return r.Config.AddPolicyException(checkName, targetPath, bug, description)
}

func (r *FixerRenderer) addAllowlistEntry(licenseName, projectPath, bug, description string) (string, error) {
	if r.Config == nil {
		return "", fmt.Errorf("config is nil")
	}
	return r.Config.AddAllowlistEntry(projectPath, licenseName, bug, description)
}

func (r *FixerRenderer) PrintSummary() {
	if len(r.FixedCount) == 0 {
		fmt.Println("\n✨ No issues found. Everything looks good!")
		return
	}

	fmt.Printf("\n✅ Applied fixes for the following categories:\n")

	var categories []string
	for cat := range r.FixedCount {
		categories = append(categories, cat)
	}
	sort.Strings(categories)

	for _, cat := range categories {
		paths := r.FixedCount[cat]
		fmt.Printf("\n[%s]\n", cat)
		sort.Strings(paths)
		for _, p := range paths {
			rel, _ := filepath.Rel(r.FuchsiaDir, p)
			if rel == "" {
				rel = p
			}
			fmt.Printf("  - %s\n", rel)
		}
	}

	if len(r.NewConfigFiles) > 0 {
		fmt.Printf("\n⚠️  ACTION REQUIRED:\n")
		fmt.Printf("You must file an OSRB bug for any newly added policy exceptions or allowlist entries.\n")
		fmt.Printf("Please update the 'bug' field in these files:\n")
		sort.Strings(r.NewConfigFiles)
		for _, path := range r.NewConfigFiles {
			rel, _ := filepath.Rel(r.FuchsiaDir, path)
			if rel == "" {
				rel = path
			}
			fmt.Printf("  - %s\n", rel)
		}
	}
}

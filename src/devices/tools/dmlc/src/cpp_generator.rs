    fn make_schema(structs: Vec<StructDef>) -> Schema {
        let mut struct_map = HashMap::new();
        for s in structs {
            struct_map.insert(s.name.clone(), s);
        }
        Schema {
            id: "test_metadata".to_string(),
            enums: HashMap::new(),
            structs: struct_map,
            root_layout: StructDef { name: "Root".to_string(), fields: vec![] },
        }
    }

    #[test]
    fn test_topological_sort_success() {
        // B has no dependencies
        let struct_b = StructDef {
            name: "StructB".to_string(),
            fields: vec![Field { name: "val".to_string(), ty: Type::Uint32, optional: false }],
        };
        // A depends on B
        let struct_a = StructDef {
            name: "StructA".to_string(),
            fields: vec![Field {
                name: "b".to_string(),
                ty: Type::Struct("StructB".to_string()),
                optional: false,
            }],
        };

        let schema = make_schema(vec![struct_a, struct_b]);
        let res = generate_cpp_parser(&[schema], "my_driver", "my_driver", "2026");
        assert!(res.is_ok());
        let (h_code, _) = res.unwrap();

        // StructB must be defined before StructA in the header
        let idx_b = h_code.find("struct StructB {").unwrap();
        let idx_a = h_code.find("struct StructA {").unwrap();
        assert!(idx_b < idx_a, "StructB must be defined before StructA");
    }


// Issues a `kill` syscall with a given signal, setting the stack to a given
// address.
// This is useful for testing how the signal stack gets setup.
void raise_with_stack(int signal, uintptr_t stack) {
  int pid = getpid();
  uint64_t new_rsp = stack;
#if defined(__x86_64__)
  __asm__ volatile(
      "movq %%rsp, %%r15\n"
      "movq %[new_rsp], %%rsp\n"
      "syscall\n"
      "movq %%r15, %%rsp\n"
      :
      : "A"(SYS_kill), "D"(pid), "S"(signal), [new_rsp] "r"(new_rsp)
      : "rcx", "rdx", "r8", "r9", "r10", "r11", "r15", "cc", "memory");
#elif defined(__aarch64__)
  __asm__ volatile(
      "mov x19, sp\n"
      "mov sp, %[new_rsp]\n"
      "mov w0, %w[pid]\n"
      "mov w1, %w[signal]\n"
      "mov w8, %[sys_kill]\n"
      "svc #0\n"
      "mov sp, x19\n"
      :
      : [pid] "r"(pid), [signal] "r"(signal), [new_rsp] "r"(new_rsp), [sys_kill] "i"(SYS_kill)
      : "x0", "x1", "x2", "x3", "x4", "x5", "x6", "x7", "x8", "x9", "x10", "x11", "x12", "x13",
        "x14", "x15", "x16", "x17", "x19", "cc", "memory");
#elif defined(__arm__)
  __asm__ volatile(
      "mov r4, sp\n"
      "mov sp, %[new_rsp]\n"
      "mov r0, %[pid]\n"
      "mov r1, %[signal]\n"
      "mov r7, %[sys_kill]\n"
      "svc #0\n"
      "mov sp, r4\n"
      :
      : [pid] "r"(pid), [signal] "r"(signal), [new_rsp] "r"(new_rsp), [sys_kill] "i"(SYS_kill)
      : "r0", "r1", "r2", "r3", "r4", "r7", "cc", "memory");
#elif defined(__riscv)
  __asm__ volatile(
      "mv s1, sp\n"
      "mv sp, %[new_rsp]\n"
      "mv a0, %[pid] \n"
      "mv a1, %[signal] \n"
      "li a7, %[sys_kill]\n"
      "ecall\n"
      "mv sp, s1\n"
      :
      : [pid] "r"(pid), [signal] "r"(signal), [new_rsp] "r"(new_rsp), [sys_kill] "i"(SYS_kill)
      : "ra", "t0", "t1", "t2", "t3", "t4", "t5", "t6", "a0", "a1", "a2", "a3", "a4", "a5", "a6",
        "a7", "s1", "memory");
#else
#error "unimplemented"
#endif
}


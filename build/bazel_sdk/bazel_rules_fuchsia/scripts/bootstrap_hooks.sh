set -eu

SCRIPT_DIR=$(dirname "${BASH_SOURCE[0]}")
VERBOSE=0

source "$SCRIPT_DIR/common.sh" || exit $?

help() {
  echo
  echo "Script used to bootstrap git hooks (Gerrit commit-msg hook and Bazel update hooks)"
  echo
  echo "Usage:"
  echo "   $(basename "$0") [<options>]"
  echo
  echo "Options:"
  echo
  echo "  -h"
  echo "     Prints this help message"
  echo "  -v"
  echo "     Uses verbose output"
  echo
}

function log {
  if [[ "$VERBOSE" -eq 1 ]]; then
    echo "$@"
  fi
}

function main() {
  while getopts ":hv" opt; do
    case ${opt} in
      'h' | '?')
        help
        exit 1
        ;;
      'v')
        VERBOSE=1
        ;;
    esac
  done

  if ! git rev-parse --git-dir &>/dev/null; then
    log "Not inside a git repository; skipping git hooks bootstrap."
    exit 0
  fi

  local git_dir
  git_dir="$(git rev-parse --git-dir)"
  mkdir -p "${git_dir}/hooks"

  # 1. Install Gerrit commit-msg hook ("commit-id" hook)
  local commit_msg_hook="${git_dir}/hooks/commit-msg"
  if [[ ! -x "${commit_msg_hook}" ]]; then
    log "Downloading Gerrit commit-msg hook..."
    if curl -s -f -Lo "${commit_msg_hook}" https://fuchsia-review.googlesource.com/tools/hooks/commit-msg || \
       curl -s -f -Lo "${commit_msg_hook}" https://gerrit-review.googlesource.com/tools/hooks/commit-msg; then
      chmod u+x "${commit_msg_hook}"
      log "Installed Gerrit commit-msg hook."
    else
      echo "Warning: Failed to download Gerrit commit-msg hook." >&2
      rm -f "${commit_msg_hook}"
    fi
  else
    log "Gerrit commit-msg hook already installed."
  fi

  # 2. Install post-checkout and post-merge hooks for Bazel update
  for hook_name in post-checkout post-merge; do
    local hook_path="${git_dir}/hooks/${hook_name}"
    if [[ -f "${hook_path}" ]] && grep -q "bootstrap_bazel.sh" "${hook_path}"; then
      log "${hook_name} hook already configured for bazel bootstrap."
      continue
    fi

    if [[ ! -f "${hook_path}" ]]; then
      echo '#!/bin/bash' > "${hook_path}"
    else
      echo '' >> "${hook_path}"
    fi

    cat >> "${hook_path}" <<'EOF'
# Automatically generated by bootstrap_hooks.sh
# Ensure bazel is up-to-date after branch checkout or merge.
ROOT_DIR="$(git rev-parse --show-toplevel 2>/dev/null)"
if [[ -n "${ROOT_DIR}" && (-e "${ROOT_DIR}/WORKSPACE" || -e "${ROOT_DIR}/WORKSPACE.bazel" || -e "${ROOT_DIR}/MODULE.bazel") ]]; then
  if [[ -x "${ROOT_DIR}/third_party/fuchsia-infra-bazel-rules/scripts/bootstrap_bazel.sh" ]]; then
    "${ROOT_DIR}/third_party/fuchsia-infra-bazel-rules/scripts/bootstrap_bazel.sh"
  fi
fi
EOF
    chmod u+x "${hook_path}"
    log "Configured ${hook_name} hook."
  done
}

main "$@"

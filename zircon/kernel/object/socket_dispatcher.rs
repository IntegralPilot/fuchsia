        expect_eq!(rights, DEFAULT_RIGHTS);
        let d0 = h0.dispatcher();
        let d1 = h1.dispatcher();

        let info0 = d0.get_info();
        expect_eq!(info0.rx_buf_available, 0); // No bytes written yet.


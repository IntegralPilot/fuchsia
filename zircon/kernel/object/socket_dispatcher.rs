    /// Tests filling stream socket to capacity, WRITABLE signal deassertion, and recovery on read.
    #[test]
    fn test_stream_socket_full_and_writable_signals() {
        let (h0, h1, _) = SocketDispatcher::create(0).expect("failed to create stream socket");
        let d0 = h0.dispatcher();
        let d1 = h1.dispatcher();

        let info = d0.get_info();
        let capacity = info.rx_buf_max;
        expect_true!(capacity > 0);

        // Fill socket almost completely.
        const CHUNK: usize = 32 * 1024;
        let (_in_mem, in_ptr) = make_user_in_pattern(CHUNK, |i| (i & 0xff) as u8).unwrap();
        let mut total_written = 0usize;

        while total_written + CHUNK <= capacity {
            let w = d0.write(in_ptr, CHUNK).expect("write chunk");
            expect_eq!(w, CHUNK);
            total_written += w;
        }

        // Top off with exact remaining bytes to reach full capacity.
        let rem = capacity - total_written;
        if rem > 0 {
            let (_rem_mem, rem_ptr) = make_user_in_pattern(rem, |_| 0xaa).unwrap();
            let w = d0.write(rem_ptr, rem).expect("write remaining");
            expect_eq!(w, rem);
            total_written += w;
        }

        expect_eq!(total_written, capacity);
        let info1 = d1.get_info();
        expect_eq!(info1.rx_buf_size, capacity);

        // Socket is now full; writer (d0) should have ZX_SOCKET_WRITABLE deasserted.
        {
            ksync::lock!(let guard0 = d0.state().peered.lock());
            let sigs0 = d0.signals_state_locked(guard0.token());
            expect_eq!(sigs0 & ZX_SOCKET_WRITABLE, 0);
        }

        // Writing when full returns SHOULD_WAIT.
        let res_overflow = d0.write(in_ptr, 1);
        expect_true!(res_overflow == Err(Status::SHOULD_WAIT));

        // Reading even 1 byte from receiver (d1) should immediately re-assert ZX_SOCKET_WRITABLE.
        let (_out_mem, out_ptr) = make_user_out(1).unwrap();
        let nread = d1.read(ReadType::Consume, out_ptr, 1).expect("read 1 byte");
        expect_eq!(nread, 1);

        {
            ksync::lock!(let guard0 = d0.state().peered.lock());
            let sigs0 = d0.signals_state_locked(guard0.token());
            expect_true!((sigs0 & ZX_SOCKET_WRITABLE) != 0);
        }

        // Test short write: attempt to write 100 bytes when only 1 byte is available.
        let (_short_mem, short_ptr) = make_user_in_pattern(100, |_| 0xbb).unwrap();
        let w_short = d0.write(short_ptr, 100).expect("short write");
        expect_eq!(w_short, 1);

        // Socket is full again.
        {
            ksync::lock!(let guard0 = d0.state().peered.lock());
            let sigs0 = d0.signals_state_locked(guard0.token());
            expect_eq!(sigs0 & ZX_SOCKET_WRITABLE, 0);
        }
    }

    /// Tests disposition state transitions, write-disabled errors, and re-enabling restrictions.
    #[test]
    fn test_disposition_state_transitions() {
        let (h0, h1, _) = SocketDispatcher::create(0).expect("failed to create stream socket");
        let d0 = h0.dispatcher();
        let d1 = h1.dispatcher();

        let (_m_mem, m_ptr) = make_user_in(b"hello").unwrap();
        let w = d0.write(m_ptr, 5).expect("write initial data");
        expect_eq!(w, 5);

        // Disable writes on d0.
        expect_ok!(d0.set_disposition(Disposition::WriteDisabled, Disposition::None));

        // d0 should have ZX_SOCKET_WRITE_DISABLED asserted and ZX_SOCKET_WRITABLE cleared.
        // d1 should have ZX_SOCKET_PEER_WRITE_DISABLED asserted.
        {
            ksync::lock!(let guard0 = d0.state().peered.lock());
            let sigs0 = d0.signals_state_locked(guard0.token());
            expect_true!((sigs0 & ZX_SOCKET_WRITE_DISABLED) != 0);
            expect_eq!(sigs0 & ZX_SOCKET_WRITABLE, 0);
        }
        {
            ksync::lock!(let guard1 = d1.state().peered.lock());
            let sigs1 = d1.signals_state_locked(guard1.token());
            expect_true!((sigs1 & ZX_SOCKET_PEER_WRITE_DISABLED) != 0);
        }

        // Writing on write-disabled socket fails with BAD_STATE.
        let res_w = d0.write(m_ptr, 5);
        expect_true!(res_w == Err(Status::BAD_STATE));

        // Re-enabling writes while unread buffered data is present must fail with BAD_STATE.
        let res_re_enable = d0.set_disposition(Disposition::WriteEnabled, Disposition::None);
        expect_true!(res_re_enable == Err(Status::BAD_STATE));

        // Read out the 5 bytes from d1.
        let (_out_mem, out_ptr) = make_user_out(5).unwrap();
        let nread = d1.read(ReadType::Consume, out_ptr, 5).expect("read buffered data");
        expect_eq!(nread, 5);

        // Now that the buffer is empty, reading again with peer write disabled returns BAD_STATE.
        let res_empty_read = d1.read(ReadType::Consume, out_ptr, 1);
        expect_true!(res_empty_read == Err(Status::BAD_STATE));

        // Now that buffer is empty, re-enabling writes on d0 succeeds.
        expect_ok!(d0.set_disposition(Disposition::WriteEnabled, Disposition::None));

        // d0 should now be writable again.
        {
            ksync::lock!(let guard0 = d0.state().peered.lock());
            let sigs0 = d0.signals_state_locked(guard0.token());
            expect_true!((sigs0 & ZX_SOCKET_WRITABLE) != 0);
            expect_eq!(sigs0 & ZX_SOCKET_WRITE_DISABLED, 0);
        }

        // Writing to d0 succeeds again.
        let w_again = d0.write(m_ptr, 5).expect("write again");
        expect_eq!(w_again, 5);
    }


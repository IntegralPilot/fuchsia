    /// Tests read and write threshold setting, retrieval, and signal transitions.
    #[test]
    fn test_read_write_thresholds_and_signals() {
        let (h0, h1, _) = SocketDispatcher::create(0).expect("failed to create stream socket");
        let d0 = h0.dispatcher();
        let d1 = h1.dispatcher();

        // Initial threshold values default to 0 (disabled).
        expect_eq!(d0.get_read_threshold(), 0);
        expect_eq!(d0.get_write_threshold(), 0);

        let info0 = d0.get_info();
        // Setting threshold beyond capacity must fail with INVALID_ARGS.
        expect_true!(d0.set_read_threshold(info0.rx_buf_max + 1) == Err(Status::INVALID_ARGS));
        expect_true!(d0.set_write_threshold(info0.rx_buf_max + 1) == Err(Status::INVALID_ARGS));

        // Setting a valid read threshold of 50 bytes.
        expect_ok!(d0.set_read_threshold(50));
        expect_eq!(d0.get_read_threshold(), 50);

        // Signal should not be active since 0 < 50.
        {
            ksync::lock!(let guard0 = d0.state().peered.lock());
            let sigs0 = d0.signals_state_locked(guard0.token());
            expect_eq!(sigs0 & ZX_SOCKET_READ_THRESHOLD, 0);
        }

        // Write 30 bytes into d0 from d1 (below read threshold).
        let (_b30_mem, b30_ptr) = make_user_in(&[0xaa_u8; 30]).unwrap();
        let w = d1.write(b30_ptr, 30).expect("write 30");
        expect_eq!(w, 30);

        {
            ksync::lock!(let guard0 = d0.state().peered.lock());
            let sigs0 = d0.signals_state_locked(guard0.token());
            expect_true!((sigs0 & ZX_SOCKET_READABLE) != 0);
            expect_eq!(sigs0 & ZX_SOCKET_READ_THRESHOLD, 0);
        }

        // Write 25 more bytes (total 55 >= 50 threshold).
        let (_b25_mem, b25_ptr) = make_user_in(&[0xbb_u8; 25]).unwrap();
        let w = d1.write(b25_ptr, 25).expect("write 25");
        expect_eq!(w, 25);

        {
            ksync::lock!(let guard0 = d0.state().peered.lock());
            let sigs0 = d0.signals_state_locked(guard0.token());
            expect_true!((sigs0 & ZX_SOCKET_READ_THRESHOLD) != 0);
        }

        // Read 10 bytes from d0 (leaving 45 bytes, falling below the 50 threshold).
        let (_r10_mem, r10_ptr) = make_user_out(10).unwrap();
        let nread = d0.read(ReadType::Consume, r10_ptr, 10).expect("read 10");
        expect_eq!(nread, 10);

        {
            ksync::lock!(let guard0 = d0.state().peered.lock());
            let sigs0 = d0.signals_state_locked(guard0.token());
            expect_eq!(sigs0 & ZX_SOCKET_READ_THRESHOLD, 0);
            expect_true!((sigs0 & ZX_SOCKET_READABLE) != 0);
        }

        // Setting read threshold to 0 disables it and clears signal unconditionally.
        expect_ok!(d0.set_read_threshold(0));
        expect_eq!(d0.get_read_threshold(), 0);

        // Test write threshold on d1 (which tracks available space in d0).
        expect_ok!(d1.set_write_threshold(100));
        expect_eq!(d1.get_write_threshold(), 100);

        {
            ksync::lock!(let guard1 = d1.state().peered.lock());
            let sigs1 = d1.signals_state_locked(guard1.token());
            // Since d0 has ample space (> 100 bytes available), write threshold signal is asserted.
            expect_true!((sigs1 & ZX_SOCKET_WRITE_THRESHOLD) != 0);
        }

        // Fill d0 almost to capacity so available space drops below 100 bytes.
        let to_fill = info0.rx_buf_max - 50;
        let (_fill_mem, fill_ptr) = make_user_in_pattern(to_fill, |_| 0xcc).unwrap();
        let w = d1.write(fill_ptr, to_fill).expect("write fill");
        expect_eq!(w, to_fill);

        {
            ksync::lock!(let guard1 = d1.state().peered.lock());
            let sigs1 = d1.signals_state_locked(guard1.token());
            // Available space in d0 is now 50 (< 100 write threshold), so signal should be de-asserted.
            expect_eq!(sigs1 & ZX_SOCKET_WRITE_THRESHOLD, 0);
            expect_true!((sigs1 & ZX_SOCKET_WRITABLE) != 0);
        }

        // Disabling write threshold by setting it to 0.
        expect_ok!(d1.set_write_threshold(0));
        expect_eq!(d1.get_write_threshold(), 0);

        {
            ksync::lock!(let guard1 = d1.state().peered.lock());
            let sigs1 = d1.signals_state_locked(guard1.token());
            expect_eq!(sigs1 & ZX_SOCKET_WRITE_THRESHOLD, 0);
        }
    }

    /// Tests socket operations and signal handling when the peer endpoint is closed.
    #[test]
    fn test_closed_peer_operations() {
        let (h0, h1, _) = SocketDispatcher::create(0).expect("failed to create stream socket");
        let d0 = h0.dispatcher();
        let d1 = h1.dispatcher();

        // Write some data from d0 to d1 before closing d0.
        let (_test_mem, test_ptr) = make_user_in(&[42u8; 16]).unwrap();
        let written = d0.write(test_ptr, 16).expect("write test data");
        expect_eq!(written, 16);

        // Close peer endpoint d0.
        drop(h0);

        // Peer closing asserts ZX_SOCKET_PEER_CLOSED and de-asserts ZX_SOCKET_WRITABLE on d1.
        {
            ksync::lock!(let guard1 = d1.state().peered.lock());
            let sigs1 = d1.signals_state_locked(guard1.token());
            expect_true!((sigs1 & ZX_SOCKET_PEER_CLOSED) != 0);
            expect_eq!(sigs1 & ZX_SOCKET_WRITABLE, 0);
        }

        // Writing to d1 when peer is closed must return PEER_CLOSED (even for 0 bytes).
        let res_w = d1.write(test_ptr, 16);
        expect_true!(res_w == Err(Status::PEER_CLOSED));
        let res_w0 = d1.write(test_ptr, 0);
        expect_true!(res_w0 == Err(Status::PEER_CLOSED));

        // Setting write threshold when peer is closed must return PEER_CLOSED.
        let res_wt = d1.set_write_threshold(50);
        expect_true!(res_wt == Err(Status::PEER_CLOSED));

        // Getting write threshold still succeeds.
        expect_eq!(d1.get_write_threshold(), 0);

        // Setting read threshold still works on closed peer.
        expect_ok!(d1.set_read_threshold(10));
        expect_eq!(d1.get_read_threshold(), 10);

        // Getting socket info on closed peer returns rx info and zeroed tx capacity.
        let info = d1.get_info();
        expect_eq!(info.rx_buf_size, 16);
        expect_eq!(info.tx_buf_max, 0);
        expect_eq!(info.tx_buf_size, 0);

        // Buffered data can still be read out completely.
        let (r_mem, r_ptr) = make_user_out(16).unwrap();
        let nread = d1.read(ReadType::Consume, r_ptr, 16).expect("read remaining data");
        expect_eq!(nread, 16);
        let b = read_user_mem(&r_mem, 16).unwrap();
        expect_true!(*b == [42u8; 16]);

        // Once empty and peer is closed, reading returns PEER_CLOSED.
        let res_r = d1.read(ReadType::Consume, r_ptr, 16);
        expect_true!(res_r == Err(Status::PEER_CLOSED));

        // Setting disposition on closed peer: no-op disposition succeeds.
        expect_ok!(d1.set_disposition(Disposition::None, Disposition::None));
        expect_ok!(d1.set_disposition(Disposition::WriteDisabled, Disposition::None));
    }


/// Represents the disposition of a socket endpoint's write status.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
#[repr(u32)]
pub enum Disposition {
    /// No change in disposition.
    None = 0,
    /// Disables writes on the socket endpoint.
    WriteDisabled = ZX_SOCKET_DISPOSITION_WRITE_DISABLED,
    /// Enables writes on the socket endpoint.
    WriteEnabled = ZX_SOCKET_DISPOSITION_WRITE_ENABLED,
}

impl TryFrom<u32> for Disposition {
    type Error = Status;

    /// Converts a raw uint32_t disposition into a `Disposition` enum variant.
    fn try_from(disposition: u32) -> Result<Self, Status> {
        match disposition {
            0 => Ok(Self::None),
            ZX_SOCKET_DISPOSITION_WRITE_DISABLED => Ok(Self::WriteDisabled),
            ZX_SOCKET_DISPOSITION_WRITE_ENABLED => Ok(Self::WriteEnabled),
            _ => Err(Status::INVALID_ARGS),
        }
    }
}

/// Signal masks generated by a [`Disposition`].
#[derive(Clone, Copy, Debug, Default, PartialEq, Eq)]
struct SignalMasks {
    /// Signals to clear on the target endpoint.
    clear: zx_signals_t,
    /// Signals to set on the target endpoint.
    set: zx_signals_t,
    /// Signals to clear on the peer endpoint.
    peer_clear: zx_signals_t,
    /// Signals to set on the peer endpoint.
    peer_set: zx_signals_t,
}

impl Disposition {
    /// Returns the signal masks corresponding to this disposition.
    fn signal_masks(self) -> SignalMasks {
        match self {
            Self::WriteDisabled => SignalMasks {
                clear: ZX_SOCKET_WRITABLE,
                set: ZX_SOCKET_WRITE_DISABLED,
                peer_clear: 0,
                peer_set: ZX_SOCKET_PEER_WRITE_DISABLED,
            },
            Self::WriteEnabled => SignalMasks {
                clear: ZX_SOCKET_WRITE_DISABLED,
                set: ZX_SOCKET_WRITABLE,
                peer_clear: ZX_SOCKET_PEER_WRITE_DISABLED,
                peer_set: 0,
            },
            Self::None => SignalMasks::default(),
        }
    }
}

/// Specifies the type of read operation (consume or peek).
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum ReadType {
    /// Consumes read data from the socket.
    Consume,
    /// Peeks data without consuming it from the socket buffer.
    Peek,
}

/// Synchronization and state layout for `SocketDispatcher`.
///
/// The shared `mu` lock protects all state members below.
#[guarded]
#[pin_data(PinnedDrop)]
#[repr(C)]
pub struct SocketDispatcherState {
    canary: Canary<{ fbl::magic(b"SOCK") }>,

    #[pin]
    pub peered: PeeredState<SocketDispatcher>,

    flags: u32,
    #[guarded_by(mu)]
    read_disabled: bool,

    #[guarded_by(mu)]
    read_threshold: usize,
    #[guarded_by(mu)]
    write_threshold: usize,

    #[guarded_by(mu)]
    #[pin]
    data: MBufChain,

    #[mutex(PeerHolderMuClass<SocketDispatcher>)]
    pub mu: KMutex<PhantomMutex>,
}

impl SocketDispatcherState {
    /// Initializes `SocketDispatcherState` with peer holder and creation flags.
    pub fn init(
        holder: RefPtr<PeerHolder<SocketDispatcher>>,
        flags: u32,
    ) -> impl PinInit<Self, Infallible> {
        DISPATCHER_SOCKET_CREATE_COUNT.add(1);
        pin_init!(Self {
            canary: Canary::new(),
            peered <- PeeredState::init(holder),
            flags,
            read_disabled: false.into(),
            read_threshold: 0.into(),
            write_threshold: 0.into(),
            data <- ksync::kcell_init(MBufChain::new()),
            mu: KMutex::new(PhantomMutex),
        })
    }
}

#[pinned_drop]
impl PinnedDrop for SocketDispatcherState {
    fn drop(self: Pin<&mut Self>) {
        DISPATCHER_SOCKET_DESTROY_COUNT.add(1);
    }
}

